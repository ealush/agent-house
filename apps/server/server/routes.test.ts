// The HTTP API's shape, pinned. ah-native and the web client depend on these paths and
// verbs: a route added, removed or changed shows up as a diff of packages/protocol/api-routes.txt,
// reviewed with the change. Regenerate after a deliberate change:
//   AH_UPDATE_ROUTES=1 node --test server/routes.test.ts
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { apiRoutes, type ApiDeps } from './api/index.ts';
import { match, type Route } from './api/router.ts';
import { PUBLIC_ROUTES } from './admission.ts';

const MANIFEST = fileURLToPath(new URL('../../../packages/protocol/api-routes.txt', import.meta.url));

// Building the tables only closes over the services; nothing is called until a request.
const { auth, routes } = apiRoutes({} as ApiDeps);
const all = [...auth, ...routes];

const line = (r: Route) => `${r.method.padEnd(6)} ${r.path.source}${r.public ? '  [public]' : ''}`;

/** A concrete path a route's pattern matches: each capture filled with a plausible value. */
function sample(r: Route): string {
  let s = r.path.source.replace(/^\^|\$$/g, '').replace(/\\\//g, '/');
  s = s.replace(/\[[^\]]*\](\{\d+,\d+\}|\+|\*)?/g, (_, q) => (q ? 'x1' : 'x'));
  s = s.replace(/\\d(\{\d+,\d+\}|\+)/g, '7').replace(/\\w(\{\d+,\d+\}|\+)/g, 'x1');
  // Innermost groups first: an optional part is left out, a group is its first alternative.
  for (let prev = ''; prev !== s; ) {
    prev = s;
    s = s.replace(/\(\?:[^()]*\)\?/g, '').replace(/\((?:\?:)?([^()|]*)(\|[^()]*)?\)/g, '$1');
  }
  return s;
}

test('the API surface matches packages/protocol/api-routes.txt', () => {
  const now = `# Every HTTP route under /api, in match order (server/api/*.ts). Generated by\n# server/routes.test.ts; a change here is an API change: review it as one.\n# Sub-routers not listed: /api/review, /api/portable, /api/migrations, /api/jobs, /api/notes.\n${all.map(line).join('\n')}\n`;
  if (process.env.AH_UPDATE_ROUTES === '1') writeFileSync(MANIFEST, now);
  assert.equal(now, readFileSync(MANIFEST, 'utf8'));
});

test('a route is public exactly when admission lets it through signed out', () => {
  const pub = all.filter((r) => r.public);
  assert.deepEqual(routes.filter((r) => r.public), [], 'only /api/auth has public routes');
  // /api/hello is answered before any table (it says whether auth is on at all).
  const expected = [...PUBLIC_ROUTES].filter((r) => r !== 'GET /api/hello').sort();
  const actual = pub.map((r) => `${r.method} ${sample(r)}`).sort();
  assert.deepEqual(actual, expected);
});

test('every route is reachable: none is shadowed by an earlier one', () => {
  for (const table of [auth, routes]) {
    for (const r of table) {
      const path = sample(r);
      assert.ok(r.path.test(path), `sample ${path} doesn't match ${r.path.source}`);
      assert.equal(match(table, r.method, path)?.route, r, `${r.method} ${path} is answered by an earlier route`);
    }
  }
});

test('no two routes share a method and pattern', () => {
  const seen = new Set<string>();
  for (const r of all) {
    const k = `${r.method} ${r.path.source}`;
    assert.ok(!seen.has(k), k);
    seen.add(k);
  }
});

// Every action is in the audit log (docs/spec/13-conductor.md): a route that changes
// something says so, unless it's listed here with why not. /api/auth is audited by
// auth.ts itself (sign-ins, codes, devices, passkeys, tokens, the password).
const NOT_AUDITED: Record<string, string> = {
  'POST ^\\/api\\/sessions\\/([\\w-]{1,40})\\/pin$': 'your list’s layout',
  'POST ^\\/api\\/sessions\\/([\\w-]{1,40})\\/order$': 'your list’s layout',
  'POST ^\\/api\\/focus$': 'which session a device shows, several times a minute',
  'PUT ^\\/api\\/sessions\\/([\\w-]{1,40})\\/draft$': 'an unsent draft, as you type',
  'POST ^\\/api\\/usage\\/refresh$': 're-reads transcripts; changes nothing',
  'POST ^\\/api\\/subscriptions\\/models$': 'a read (lists a provider’s models)',
  'POST ^\\/api\\/voice\\/models$': 'a read (lists a provider’s models)',
  'POST ^\\/api\\/push\\/status$': 'a read (this device’s alert settings)',
  'PUT ^\\/api\\/windows\\/(@\\d+)\\/chat\\/subscription$': 'which subscription a side chat uses',
  'DELETE ^\\/api\\/windows\\/(@\\d+)\\/chat$': 'clears a side chat’s local history',
  'PUT ^\\/api\\/push\\/apns\\/activity$': 'a Live Activity’s token, per session and device, often',
  'DELETE ^\\/api\\/push\\/apns\\/activity\\/([^/]+)$': 'the same, ended',
};

test('every route that changes something is audited, or says why not', () => {
  const unaudited = routes.filter((r) => r.method !== 'GET' && !r.run.toString().includes('audit(')).map((r) => `${r.method} ${r.path.source}`);
  assert.deepEqual(unaudited.filter((k) => !NOT_AUDITED[k]), [], 'audit these, or list them in NOT_AUDITED with a reason');
  assert.deepEqual(Object.keys(NOT_AUDITED).filter((k) => !unaudited.includes(k)), [], 'stale exemptions');
});
